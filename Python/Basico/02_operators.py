### Operadores en Logicos de Python ###

print(3 > 4 and "Hola" > "Python") # Mayor que
print(3 < 4 or "Hola" > "Python") # Menor que
print(3 < 4 or "Hola" > "Python") # Menor que
print(not(3 < 4)) # Negación de la comparación
print(not("Hola" > "Python")) # Negación de la comparación