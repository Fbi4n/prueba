### Operadores en Aritmética de Python ###
print(2+2) # Suma
print(10-6) # Resta
print(4*1) # Multiplicación
print(8/2) # División
print(16%3) # Módulo o residuo  
print(8//2) # División entera 
print(4**1) # Potencia
print(2**3 + 3 -7 / 1 //4) 

print("----------------")

print("Hola " + "Python") # Concatenación de strings
print("Hola " * 3) # Repetición de strings
print("Hola " + str(3)) # Concatenación de string con número convertido a string

my_float = 2.5 * 2
print("Hola " * int(my_float)) # Repetición de string con número convertido a entero

